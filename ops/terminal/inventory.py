"""Turn docs/terminal-inventory.tsv into frontend/lib/terminal/inventory.ts.

The TSV lists every Bloomberg function code found on public cheat sheets
(sources in docs/terminal-inventory-sources.txt), each classified as live,
alias (the same as another code), build (buildable on free data, not yet
built) or impossible (with the reason). Codes the hand-written registry in
functions.ts already defines are skipped, so building a code is: write its
view, add it to functions.ts, and run this again.

    python3 ops/terminal/inventory.py
"""

import csv
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
TSV = ROOT / "docs" / "terminal-inventory.tsv"
FUNCTIONS = ROOT / "frontend" / "lib" / "terminal" / "functions.ts"
OUT = ROOT / "frontend" / "lib" / "terminal" / "inventory.ts"

GROUPS = {
    "Company": "Company", "Equity": "Markets", "Options": "Options", "Fixed income": "Fixed income", "Munis": "Fixed income",
    "Mortgages": "Fixed income", "Credit": "Credit", "Rates & FX": "Rates & FX", "Commodities": "Commodities",
    "Economy": "Economy", "News": "News", "Screening": "Screening", "Portfolio": "Portfolio", "Trading": "Trading",
    "Funds": "Funds", "Deals": "Deals", "Technical": "Technical", "Tools": "Tools", "Other": "Tools",
}

REASONS = {
    "dealer-prices": "Prices come from dealers and are not free.",
    "proprietary-dataset": "It is a licensed or proprietary database.",
    "bloomberg-content": "Bloomberg's own staff write or collect it.",
    "network": "It is a network; its value is the other people on it.",
    "account": "It needs a broker or exchange account.",
    "terminal-only": "It is about the Bloomberg terminal itself.",
    "retired": "Bloomberg has retired it.",
}


def main() -> None:
    defined = set(re.findall(r"(?:live|impossible)\('([A-Z0-9]+)'", FUNCTIONS.read_text()))
    rows = list(csv.DictReader(TSV.open(), delimiter="\t"))
    out = []
    for r in rows:
        code = r["code"]
        if code in defined:
            continue
        entry = {"code": code, "name": r["name"], "group": GROUPS.get(r["area"], "Tools"),
                 "security": r["needs_security"] == "yes"}
        if r["status"] == "alias":
            entry.update(status="alias", target=r["target"])
        elif r["status"] == "build":
            entry.update(status="planned", batch=r["batch"], why=r["plan"])
        elif r["status"] == "impossible":
            why = r["why"].strip() or REASONS.get(r["reason"], "")
            entry.update(status="impossible", why=why)
        else:                       # 'live' in the TSV but not defined here: treat as still to build
            entry.update(status="planned", batch="unsorted", why=r["plan"] or r["name"])
        out.append(entry)
    OUT.write_text(
        "// Generated by ops/terminal/inventory.py from docs/terminal-inventory.tsv. Do not edit.\n"
        "// Every public Bloomberg code that functions.ts does not define by hand.\n\n"
        "import type { Fn } from './functions'\n\n"
        f"export const INVENTORY: Fn[] = {json.dumps(out, indent=1, ensure_ascii=False)}\n")
    counts: dict[str, int] = {}
    for e in out:
        counts[e["status"]] = counts.get(e["status"], 0) + 1
    print(f"{len(out)} codes written: {counts}")


if __name__ == "__main__":
    main()
